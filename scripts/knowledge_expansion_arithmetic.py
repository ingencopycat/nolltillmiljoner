"""Independent Decimal oracles for synthetic prose, not runtime formula execution."""
from decimal import Decimal as D
from pathlib import Path
import json
OUT=Path(__file__).resolve().parents[1]/'docs/qa/knowledge-expansion'
groups={}
def check(group,label,value,expected):
    assert value==D(expected),(group,label,value,expected)
    groups.setdefault(group,[]).append({'expression':label,'result':str(value),'expected':expected})
check('1d','2.20 - 2.00',D('2.20')-D('2.00'),'0.20')
check('1d','(2.20 - 2.00) / abs(2.00) * 100',(D('2.20')-D('2.00'))/abs(D('2.00'))*100,'10')
check('1d','20 + 25 + 30 + 35',sum(map(D,['20','25','30','35'])),'110')
check('1d','invalid overlapping sum: 20 + 45 + 75 + 110',sum(map(D,['20','45','75','110'])),'250')
check('1d','45 - 20',D(45)-D(20),'25')
check('1d','75 - 45',D(75)-D(45),'30')
check('1d','110 + 55 - 45',D(110)+D(55)-D(45),'120')
check('2a','real 10/4 rounded percent',((D('1.10')/D('1.04')-1)*100).quantize(D('.01')),'5.77')
check('2a','real 8/3 rounded percent',((D('1.08')/D('1.03')-1)*100).quantize(D('.01')),'4.85')
check('2a','100 * 1.5 * .5',D(100)*D('1.5')*D('.5'),'75')
check('2a','sqrt(.75)-1 percent rounded',((D('.75').sqrt()-1)*100).quantize(D('.01')),'-13.40')
check('2a','drawdown 70/100-1',D(70)/100-1,'-.30')
for loss,expected in [('.1','11.11'),('.2','25.00'),('.5','100.00'),('.8','400.00')]:
    check('2a','recovery percent for loss '+loss,((1/(1-D(loss))-1)*100).quantize(D('.01')),expected)
check('2a','50 after +50 percent',D(50)*D('1.5'),'75')
check('2a','leveraged up equity',D(150)*D('1.1')-50,'115')
check('2a','leveraged down equity',D(150)*D('.9')-50,'85')
check('2a','beginning contribution',D(1000)*D('1.01'),'1010')
check('2a','NTM net fee return percent',(D('1.08')*D('.99')-1)*100,'6.92')
check('2bc','ownership 10/100 percent',D(10)/100*100,'10')
check('2bc','ownership after 25 new shares percent',D(10)/125*100,'8')
check('2bc','portfolio-weighted overlap percent',D('.5')*10+D('.5')*8,'9')
check('3a','YoY 104/100-1 percent',(D(104)/100-1)*100,'4')
check('3a','MoM 104/103-1 percent rounded',((D(104)/103-1)*100).quantize(D('.01')),'0.97')
check('3a','4 to 3 percentage points',D(3)-4,'-1')
check('3a','revision percentage points',D('2.3')-D('2.0'),'.3')
check('3b','mean 8 10 12',(D(8)+10+12)/3,'10')
check('3b','mean 9 10 11',(D(9)+10+11)/3,'10')
check('3b','old interval width',D(11)-10,'1')
check('3b','new interval width',D(12)-11,'1')
check('3b','old midpoint',(D(10)+11)/2,'10.5')
check('3b','new midpoint',(D(11)+12)/2,'11.5')
for eps,pe,value in [(10,20,200),(10,25,250),(10,30,300),(8,25,200),(12,25,300)]:
    check('3b',f'EPS {eps} * PE {pe}',D(eps)*pe,str(value))
check('3b','synthetic additive bridge residual',D(120)-100-8-2,'10')
check('later-a','EBITDA 1000-700',D(1000)-700,'300')
check('later-a','EBIT 1000-700-100',D(1000)-700-100,'200')
check('later-a','gross margin percent',(D(1000)-600)/1000*100,'40')
check('later-a','margin percentage points',D(44)-40,'4')
check('later-a','margin relative growth percent',(D(44)/40-1)*100,'10')
check('later-a','EV debt example',D(1000)+300-100,'1200')
check('later-a','EV net cash example',D(1000)+100-300,'800')
check('later-a','PEG percent-number convention',D(30)/30,'1')
check('later-a','PEG wrong decimal scale',D(30)/D('.30'),'100')
check('later-b','100 discounted five years at 5 percent',(D(100)/D('1.05')**5).quantize(D('.01')),'78.35')
check('later-b','100 discounted five years at 10 percent',(D(100)/D('1.10')**5).quantize(D('.01')),'62.09')
check('later-b','withdraw after returns down then up',(D(100)*D('.8')-10)*D('1.25')-10,'77.5')
check('later-b','withdraw after returns up then down',(D(100)*D('1.25')-10)*D('.8')-10,'82')
check('later-b','no withdrawals',D(100)*D('.8')*D('1.25'),'100')
check('later-b','market cap low price',D(10)*1000,'10000')
check('later-b','market cap higher price',D(100)*50,'5000')
check('later-b','spread',D(101)-99,'2')
check('later-b','spread midpoint percent',(D(101)-99)/((D(101)+99)/2)*100,'2')
check('later-b','split before value',D(100)*100,'10000')
check('later-b','split after value',D(200)*50,'10000')
check('later-b','diluted ownership percent',D(10)/125*100,'8')
check('later-b','eligible cap weights total',D(60)+30+10,'100')
check('tax','quarter values plus qualifying deposits',sum(map(D,['100000','110000','120000','130000','40000'])),'500000')
check('tax','capital basis',D(500000)/4,'125000')
check('tax','2026 registry rate verified',(D('.0255')+D('.01'))*D('.30'),'0.01065')
for group,checks in groups.items():
    (OUT/(group+'-arithmetic.json')).write_text(json.dumps({'passed':True,'method':'Independent Python Decimal; explicit units/timing in prose, no runtime executor added','checks':checks},indent=2)+'\n',encoding='utf8')
print('Arithmetic groups checked: '+', '.join(groups))
